import type { SyncOp } from '../../domain/syncOp'
import { isExpenseOpParticipant, isExpenseParticipant } from '../../domain/privacy'
import type { Expense } from '../../domain/entities'

export type NotificationPermissionStatus = 'granted' | 'denied' | 'default' | 'unsupported'

export interface InAppToast {
  id: string
  title: string
  body: string
  type?: 'info' | 'success' | 'warning'
  timestamp: number
}

type ToastListener = (toast: InAppToast) => void
type NotificationPreferenceListener = (enabled: boolean) => void

export interface NotifyRemoteOpsOptions {
  localDeviceId?: string
  isMe?: (id: string) => boolean
  myName?: string
  myHandle?: string
  isInitialSync?: boolean
  maxAgeMicros?: number
  getExpenseById?: (id: string) => Expense | undefined
}

export class NotificationService {
  private enabledState: boolean = true
  private toastListeners = new Set<ToastListener>()
  private prefListeners = new Set<NotificationPreferenceListener>()

  constructor() {
    if (typeof localStorage !== 'undefined') {
      const saved = localStorage.getItem('splitpay_notifications_enabled')
      if (saved !== null) {
        this.enabledState = saved === 'true'
      }
    }
  }

  isSupported(): boolean {
    return typeof window !== 'undefined' && 'Notification' in window
  }

  getPermission(): NotificationPermissionStatus {
    if (!this.isSupported()) return 'unsupported'
    return Notification.permission
  }

  isEnabled(): boolean {
    if (typeof localStorage !== 'undefined') {
      const saved = localStorage.getItem('splitpay_notifications_enabled')
      if (saved !== null) return saved === 'true'
    }
    return this.enabledState
  }

  setEnabled(enabled: boolean): void {
    this.enabledState = enabled
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem('splitpay_notifications_enabled', String(enabled))
    }
    for (const listener of this.prefListeners) {
      try {
        listener(enabled)
      } catch (err) {
        console.error('Error in notification preference listener:', err)
      }
    }
  }

  onPreferenceChange(listener: NotificationPreferenceListener): () => void {
    this.prefListeners.add(listener)
    return () => this.prefListeners.delete(listener)
  }

  async requestPermission(): Promise<boolean> {
    if (!this.isSupported()) return false
    try {
      const res = await Notification.requestPermission()
      return res === 'granted'
    } catch {
      return false
    }
  }

  subscribeToast(listener: ToastListener): () => void {
    this.toastListeners.add(listener)
    return () => this.toastListeners.delete(listener)
  }

  notify(
    title: string,
    options?: { body?: string; tag?: string; type?: 'info' | 'success' | 'warning' }
  ): void {
    if (!this.isEnabled()) return

    const body = options?.body || ''
    const toast: InAppToast = {
      id: `${Date.now()}_${Math.random().toString(36).substring(2, 7)}`,
      title,
      body,
      type: options?.type || 'info',
      timestamp: Date.now(),
    }

    // Always dispatch in-app toast for visibility
    for (const listener of this.toastListeners) {
      try {
        listener(toast)
      } catch (err) {
        console.error('Toast listener error:', err)
      }
    }

    // Attempt browser Web Notification if permitted
    if (this.isSupported() && Notification.permission === 'granted') {
      try {
        new Notification(title, {
          body,
          tag: options?.tag,
          icon: '/favicon.ico',
        })
      } catch (err) {
        console.debug('Browser notification display error:', err)
      }
    }
  }

  notifyRemoteOps(
    ops: SyncOp[],
    optionsOrDeviceId?: string | NotifyRemoteOpsOptions
  ): void {
    const options: NotifyRemoteOpsOptions =
      typeof optionsOrDeviceId === 'string'
        ? { localDeviceId: optionsOrDeviceId }
        : optionsOrDeviceId || {}

    // Never notify during initial synchronization catchup
    if (options.isInitialSync) return
    if (!this.isEnabled() || ops.length === 0) return

    const localDeviceId = options.localDeviceId
    const nowMicros = Date.now() * 1000
    const maxAgeMicros = options.maxAgeMicros ?? 60_000_000 // 60s max age for real-time notifications

    for (const op of ops) {
      // Don't notify if the op was generated by this device
      if (localDeviceId && op.deviceId === localDeviceId) continue

      // Ignore operations older than 60 seconds (prevents catchup replay spam)
      if (op.createdAtMicros && (nowMicros - op.createdAtMicros) > maxAgeMicros) {
        continue
      }

      if (op.kind === 'addExpense') {
        const payload = op.payload as {
          id?: string
          description?: string
          currency?: { symbol?: string; scale?: number }
          totalMinor?: number
          paidBy?: string
          shares?: Array<{ owedBy?: string; owedTo?: string }>
        }
        if (payload.id === 'e1' || op.opId.toUpperCase().includes('TEST')) continue
        // Don't notify if paid by me on another device
        if (payload.paidBy && options.isMe && options.isMe(payload.paidBy)) continue

        // Enforce INV-TRANSACTION-PRIVACY:
        // Group or 1:1 transactions are strictly visible only to participants.
        // If the user is not a participant (neither payer nor debtor in shares), suppress notification.
        if (options.isMe && !isExpenseOpParticipant(payload, undefined, options.isMe)) {
          continue
        }

        const desc = payload.description || 'Expense'
        const curr = payload.currency?.symbol || '₹'
        const scale = payload.currency?.scale || 100
        const total =
          typeof payload.totalMinor === 'number'
            ? (payload.totalMinor / scale).toFixed(2)
            : ''
        this.notify('New Expense Added', {
          body: `${desc} — ${curr}${total}`,
          type: 'info',
        })
      } else if (op.kind === 'addSettlement') {
        const payload = op.payload as {
          currency?: { symbol?: string; scale?: number }
          amountMinor?: number
          from?: string
          to?: string
        }
        // If settlement was made by me to someone else, don't notify "Payment Received"
        if (payload.from && options.isMe && options.isMe(payload.from)) continue

        // Enforce INV-TRANSACTION-PRIVACY:
        // A settlement is strictly between two parties. Suppress notification if local user is not the recipient.
        if (options.isMe && (!payload.to || !options.isMe(payload.to))) {
          continue
        }

        const curr = payload.currency?.symbol || '₹'
        const scale = payload.currency?.scale || 100
        const amount =
          typeof payload.amountMinor === 'number'
            ? (payload.amountMinor / scale).toFixed(2)
            : ''
        this.notify('Settlement Payment Received', {
          body: `Payment of ${curr}${amount} was recorded`,
          type: 'success',
        })
      } else if (op.kind === 'tombstoneExpense') {
        const payload = op.payload as { expenseId?: string }
        if (payload.expenseId && options.getExpenseById && options.isMe) {
          const exp = options.getExpenseById(payload.expenseId)
          if (exp && !isExpenseParticipant(exp, undefined, options.isMe)) {
            continue
          }
        }
        this.notify('Expense Cancelled', {
          body: 'An expense was marked as cancelled by a collaborator',
          type: 'warning',
        })
      } else if (op.kind === 'addPerson') {
        const payload = op.payload as { id?: string; name?: string; handle?: string }
        const id = payload.id || ''
        const name = (payload.name || '').trim()
        const handle = (payload.handle || '').trim().toLowerCase().replace(/^@/, '')
        const cleanMyHandle = (options.myHandle || '').trim().toLowerCase().replace(/^@/, '')
        const cleanMyName = (options.myName || '').trim().toLowerCase()

        const isMe =
          (id && options.isMe && options.isMe(id)) ||
          (name && cleanMyName && name.toLowerCase() === cleanMyName) ||
          (handle && cleanMyHandle && handle === cleanMyHandle) ||
          name === 'You' ||
          name === 'Guest User' ||
          name === 'SplitPay Friend' ||
          name.toLowerCase() === 'test' ||
          name.toLowerCase() === 'demo' ||
          id.startsWith('invited_') ||
          id === 'p1' ||
          id === 'test_p'

        if (!isMe && name) {
          this.notify('Friend Connected', {
            body: `${name} is now in your ledger network`,
            type: 'info',
          })
        }
      }
    }
  }
}

export const defaultNotificationService = new NotificationService()
