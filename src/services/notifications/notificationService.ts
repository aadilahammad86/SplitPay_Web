import type { SyncOp } from '../../domain/syncOp'

export type NotificationPermissionStatus = 'granted' | 'denied' | 'default' | 'unsupported'

export interface InAppToast {
  id: string
  title: string
  body: string
  type?: 'info' | 'success' | 'warning'
  timestamp: number
}

type ToastListener = (toast: InAppToast) => void
type NotificationPreferenceListener = (enabled: boolean) => void

export class NotificationService {
  private enabledState: boolean = true
  private toastListeners = new Set<ToastListener>()
  private prefListeners = new Set<NotificationPreferenceListener>()

  constructor() {
    if (typeof localStorage !== 'undefined') {
      const saved = localStorage.getItem('splitpay_notifications_enabled')
      if (saved !== null) {
        this.enabledState = saved === 'true'
      }
    }
  }

  isSupported(): boolean {
    return typeof window !== 'undefined' && 'Notification' in window
  }

  getPermission(): NotificationPermissionStatus {
    if (!this.isSupported()) return 'unsupported'
    return Notification.permission
  }

  isEnabled(): boolean {
    if (typeof localStorage !== 'undefined') {
      const saved = localStorage.getItem('splitpay_notifications_enabled')
      if (saved !== null) return saved === 'true'
    }
    return this.enabledState
  }

  setEnabled(enabled: boolean): void {
    this.enabledState = enabled
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem('splitpay_notifications_enabled', String(enabled))
    }
    for (const listener of this.prefListeners) {
      try {
        listener(enabled)
      } catch (err) {
        console.error('Error in notification preference listener:', err)
      }
    }
  }

  onPreferenceChange(listener: NotificationPreferenceListener): () => void {
    this.prefListeners.add(listener)
    return () => this.prefListeners.delete(listener)
  }

  async requestPermission(): Promise<boolean> {
    if (!this.isSupported()) return false
    try {
      const res = await Notification.requestPermission()
      return res === 'granted'
    } catch {
      return false
    }
  }

  subscribeToast(listener: ToastListener): () => void {
    this.toastListeners.add(listener)
    return () => this.toastListeners.delete(listener)
  }

  notify(
    title: string,
    options?: { body?: string; tag?: string; type?: 'info' | 'success' | 'warning' }
  ): void {
    if (!this.isEnabled()) return

    const body = options?.body || ''
    const toast: InAppToast = {
      id: `${Date.now()}_${Math.random().toString(36).substring(2, 7)}`,
      title,
      body,
      type: options?.type || 'info',
      timestamp: Date.now(),
    }

    // Always dispatch in-app toast for visibility
    for (const listener of this.toastListeners) {
      try {
        listener(toast)
      } catch (err) {
        console.error('Toast listener error:', err)
      }
    }

    // Attempt browser Web Notification if permitted
    if (this.isSupported() && Notification.permission === 'granted') {
      try {
        new Notification(title, {
          body,
          tag: options?.tag,
          icon: '/favicon.ico',
        })
      } catch (err) {
        console.debug('Browser notification display error:', err)
      }
    }
  }

  notifyRemoteOps(ops: SyncOp[], localDeviceId?: string): void {
    if (!this.isEnabled() || ops.length === 0) return

    for (const op of ops) {
      // Don't notify if the op was generated by this device
      if (localDeviceId && op.deviceId === localDeviceId) continue

      if (op.kind === 'addExpense') {
        const payload = op.payload as {
          description?: string
          currency?: { symbol?: string; scale?: number }
          totalMinor?: number
        }
        const desc = payload.description || 'Expense'
        const curr = payload.currency?.symbol || '₹'
        const scale = payload.currency?.scale || 100
        const total =
          typeof payload.totalMinor === 'number'
            ? (payload.totalMinor / scale).toFixed(2)
            : ''
        this.notify('New Expense Added', {
          body: `${desc} — ${curr}${total}`,
          type: 'info',
        })
      } else if (op.kind === 'addSettlement') {
        const payload = op.payload as {
          currency?: { symbol?: string; scale?: number }
          amountMinor?: number
        }
        const curr = payload.currency?.symbol || '₹'
        const scale = payload.currency?.scale || 100
        const amount =
          typeof payload.amountMinor === 'number'
            ? (payload.amountMinor / scale).toFixed(2)
            : ''
        this.notify('Settlement Payment Received', {
          body: `Payment of ${curr}${amount} was recorded`,
          type: 'success',
        })
      } else if (op.kind === 'tombstoneExpense') {
        this.notify('Expense Cancelled', {
          body: 'An expense was marked as cancelled by a collaborator',
          type: 'warning',
        })
      } else if (op.kind === 'addPerson') {
        const payload = op.payload as { name?: string }
        const name = payload.name || 'A friend'
        if (name !== 'You' && !name.startsWith('invited_')) {
          this.notify('Friend Connected', {
            body: `${name} is now in your ledger network`,
            type: 'info',
          })
        }
      }
    }
  }
}

export const defaultNotificationService = new NotificationService()
